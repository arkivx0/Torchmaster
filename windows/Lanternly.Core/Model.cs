using System.Reflection;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Lanternly.Core;

[Flags] public enum Caps { None = 0, OnOff = 1, Dim = 2, Temp = 4, Color = 8, Hub = 16 }
public enum Via { None, Ble }

public sealed class Bulb
{
    public string Name { get; set; } = "";
    public ushort MeshId { get; set; }          // node address inside the home's mesh (1..255 typical)
    public int Type { get; set; }
    public string Mac { get; set; } = "";       // BLE MAC (AA:BB:...)
    [JsonIgnore] public Caps Caps => DeviceCaps.For(Type);
    [JsonIgnore] public BulbState? State { get; set; }
    [JsonIgnore] public Via Via { get; set; }
}

/// <summary>Last reported bulb state. Mode: color temperature 1..100, or 0xFE when showing RGB.</summary>
public sealed record BulbState(ushort MeshId, bool Online, bool On, int Brightness, int Mode, (byte R, byte G, byte B) Rgb);

public sealed class Room
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
    public List<ushort> MeshIds { get; set; } = [];
}

public sealed class Home
{
    public uint Id { get; set; }
    public string Name { get; set; } = "";
    /// <summary>Telink mesh name and password, generated by Lanternly when it adopts a reset bulb. Secret.</summary>
    public string MeshName { get; set; } = "";
    public string MeshPassword { get; set; } = "";
    public List<Room> Rooms { get; set; } = [];
    public List<Bulb> Bulbs { get; set; } = [];
}

/// <summary>Everything the app needs. Stored encrypted (DPAPI / Keystore). Unknown fields from older files (e.g. a 0.1.0 cloud token) are ignored and dropped on the next save.</summary>
public sealed class Vault
{
    public int Format { get; set; } = 1;
    public List<Home> Homes { get; set; } = [];

    static readonly JsonSerializerOptions O = new() { WriteIndented = true, DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull };
    public string ToJson() => JsonSerializer.Serialize(this, O);
    public static Vault FromJson(string s) => JsonSerializer.Deserialize<Vault>(s, O) ?? new();
}

/// <summary>Device type → capability table, generated from pycync (spec/device_caps.tsv).</summary>
public static class DeviceCaps
{
    static readonly Dictionary<int, Caps> Map = Load();
    static Dictionary<int, Caps> Load()
    {
        var d = new Dictionary<int, Caps>();
        using var s = Assembly.GetExecutingAssembly().GetManifestResourceStream("device_caps.tsv");
        if (s == null) return d;
        using var r = new StreamReader(s);
        while (r.ReadLine() is { } line) d.TryAdd(int.Parse(line.Split('\t')[0]), Parse(line.Split('\t').ElementAtOrDefault(1) ?? ""));
        return d;
    }
    public static Caps Parse(string f) => Caps.OnOff | (f.Contains('D') ? Caps.Dim : 0) | (f.Contains('T') ? Caps.Temp : 0) | (f.Contains('C') ? Caps.Color : 0) | (f.Contains('H') ? Caps.Hub : 0);
    /// <summary>Unknown types get dimming only (safe default). Type -1 = adopted locally, type unknown: show every control.</summary>
    public const int AllControls = -1;
    public static Caps For(int type) => type == AllControls ? Caps.OnOff | Caps.Dim | Caps.Temp | Caps.Color : Map.TryGetValue(type, out var c) ? c : Caps.OnOff | Caps.Dim;
    public static int Count => Map.Count;
}
